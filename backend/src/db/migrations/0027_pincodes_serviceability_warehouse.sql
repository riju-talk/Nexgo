-- Pincode directory, courier delivery windows and richer warehouse details.
-- Reference data (pincodes) ships with the schema so the pincode lookup, serviceability check,
-- rate calculator and order forms all read one source.

CREATE TABLE pincodes (
  pincode char(6) PRIMARY KEY CHECK (pincode ~ '^[0-9]{6}$'),
  city text NOT NULL, state text NOT NULL, district text,
  zone text NOT NULL CHECK (zone IN ('metro', 'tier1', 'tier2', 'remote')),
  latitude numeric(8,4), longitude numeric(8,4),
  cod_available boolean NOT NULL DEFAULT true,
  is_oda boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true
);
CREATE INDEX pincodes_city_lookup ON pincodes (state, city);

-- Out-of-delivery-area pincodes are only served by couriers flagged serves_oda.
ALTER TABLE courier_services ADD COLUMN serves_oda boolean NOT NULL DEFAULT true;
ALTER TABLE courier_services ADD COLUMN delivery_tagline text;

ALTER TABLE warehouses ADD COLUMN warehouse_type text NOT NULL DEFAULT 'primary' CHECK (warehouse_type IN ('primary', 'secondary', 'fulfilment', 'returns'));
ALTER TABLE warehouses ADD COLUMN latitude numeric(8,4);
ALTER TABLE warehouses ADD COLUMN longitude numeric(8,4);
ALTER TABLE warehouses ADD COLUMN capacity_sqft integer CHECK (capacity_sqft > 0);
ALTER TABLE warehouses ADD COLUMN opens_at time;
ALTER TABLE warehouses ADD COLUMN closes_at time;
ALTER TABLE warehouses ADD COLUMN manager_name text;
ALTER TABLE warehouses ADD COLUMN notes text;
ALTER TABLE warehouses ADD COLUMN is_default boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX warehouses_one_default ON warehouses (seller_id) WHERE is_default AND is_active;
UPDATE warehouses w SET is_default = true WHERE w.id = (SELECT id FROM warehouses x WHERE x.seller_id = w.seller_id AND x.is_active ORDER BY x.created_at LIMIT 1);

-- Hard cap: an order carries at most 5 product lines (enforced here as well as in the API and bulk upload).
CREATE FUNCTION enforce_order_item_limit() RETURNS trigger AS $$
BEGIN
  IF (SELECT count(*) FROM order_items WHERE order_id = NEW.order_id) >= 5 THEN
    RAISE EXCEPTION 'An order can contain at most 5 products' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER order_items_max_five BEFORE INSERT ON order_items FOR EACH ROW EXECUTE FUNCTION enforce_order_item_limit();

